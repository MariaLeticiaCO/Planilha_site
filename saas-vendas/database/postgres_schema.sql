-- =====================================================================
-- SaaS Controle de Vendas — schema do banco (PostgreSQL / Neon na Vercel)
-- Mesmas 10 tabelas, colunas calculadas, view e setores do controle_vendas_schema.sql
-- (versão SQL Server). Os números do dashboard são calculados pelo app.
--
-- Não é preciso rodar à mão: no primeiro acesso a um banco vazio o app roda este script.
-- Idempotente: pode rodar de novo sem estragar nada.
-- Flags (Ativo etc.) são smallint 0/1, como o bit do SQL Server.
-- =====================================================================

-- 1. Setor (global, usado no onboarding)
CREATE TABLE IF NOT EXISTS "Setor" (
  "Id"                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Nome"                varchar(60)  NOT NULL,
  "Icone"               varchar(30)  NOT NULL DEFAULT '',
  "CategoriasSugeridas" varchar(400) NOT NULL DEFAULT '',
  "Ordem"               integer      NOT NULL DEFAULT 0
);

-- 2. Empresa (cada cliente do SaaS)
CREATE TABLE IF NOT EXISTS "Empresa" (
  "Id"                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Nome"                    varchar(120) NOT NULL,
  "SetorId"                 integer      NULL REFERENCES "Setor"("Id"),
  "Telefone"                varchar(20)  NULL,
  "LogoUrl"                 varchar(300) NULL,
  "Plano"                   varchar(10)  NOT NULL DEFAULT 'TESTE' CHECK ("Plano" IN ('TESTE','BASICO','PRO')),
  "StatusAssinatura"        varchar(10)  NOT NULL DEFAULT 'TRIAL' CHECK ("StatusAssinatura" IN ('TRIAL','ATIVA','VENCIDA','CANCELADA')),
  "DataFimTrial"            timestamp(0) NOT NULL,
  "DataFimAssinatura"       timestamp(0) NULL,
  "GatewayClienteId"        varchar(60)  NULL,
  "GatewayAssinaturaId"     varchar(60)  NULL,
  "PermitirEstoqueNegativo" smallint     NOT NULL DEFAULT 1,
  "OnboardingConcluido"     smallint     NOT NULL DEFAULT 0,
  "DataCadastro"            timestamp(0) NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo')
);

-- 3. Usuario
CREATE TABLE IF NOT EXISTS "Usuario" (
  "Id"                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmpresaId"            integer      NOT NULL REFERENCES "Empresa"("Id"),
  "Nome"                 varchar(120) NOT NULL,
  "Email"                varchar(160) NOT NULL UNIQUE,
  "Telefone"             varchar(20)  NULL,
  "SenhaHash"            varchar(300) NOT NULL,
  "Perfil"               varchar(10)  NOT NULL DEFAULT 'DONO' CHECK ("Perfil" IN ('DONO','VENDEDOR')),
  "Ativo"                smallint     NOT NULL DEFAULT 1,
  "TentativasFalhas"     integer      NOT NULL DEFAULT 0,
  "BloqueadoAte"         timestamp(0) NULL,
  "TokenRecuperacaoHash" varchar(64)  NULL,
  "TokenExpiraEm"        timestamp(0) NULL,
  "AceiteTermosEm"       timestamp(0) NULL,
  "UltimoAcesso"         timestamp(0) NULL,
  "DataCadastro"         timestamp(0) NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo')
);

-- 4. Categoria
CREATE TABLE IF NOT EXISTS "Categoria" (
  "Id"        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmpresaId" integer     NOT NULL REFERENCES "Empresa"("Id"),
  "Nome"      varchar(60) NOT NULL,
  "Ativo"     smallint    NOT NULL DEFAULT 1
);

-- 5. Produto (margem calculada pelo banco)
CREATE TABLE IF NOT EXISTS "Produto" (
  "Id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmpresaId"        integer       NOT NULL REFERENCES "Empresa"("Id"),
  "CategoriaId"      integer       NULL REFERENCES "Categoria"("Id"),
  "Codigo"           varchar(40)   NULL,
  "Nome"             varchar(120)  NOT NULL,
  "Custo"            numeric(12,2) NOT NULL DEFAULT 0 CHECK ("Custo" >= 0),
  "PrecoVenda"       numeric(12,2) NOT NULL DEFAULT 0 CHECK ("PrecoVenda" >= 0),
  "Estoque"          integer       NOT NULL DEFAULT 0,
  "EstoqueMinimo"    integer       NOT NULL DEFAULT 0,
  "MargemPercentual" numeric(7,2)  GENERATED ALWAYS AS (
                       CASE WHEN "PrecoVenda" > 0 THEN ROUND(("PrecoVenda" - "Custo") * 100 / "PrecoVenda", 2) ELSE 0 END
                     ) STORED,
  "FotoUrl"          varchar(300)  NULL,
  "Ativo"            smallint      NOT NULL DEFAULT 1,
  "DataCadastro"     timestamp(0)  NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo')
);

-- 6. FormaPagamento
CREATE TABLE IF NOT EXISTS "FormaPagamento" (
  "Id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmpresaId"      integer       NOT NULL REFERENCES "Empresa"("Id"),
  "Tipo"           varchar(10)   NOT NULL CHECK ("Tipo" IN ('PIX','DINHEIRO','DEBITO','CREDITO','CREDIARIO')),
  "Nome"           varchar(40)   NOT NULL,
  "TaxaPercentual" numeric(5,2)  NOT NULL DEFAULT 0 CHECK ("TaxaPercentual" BETWEEN 0 AND 100),
  "TaxaFixa"       numeric(10,2) NOT NULL DEFAULT 0 CHECK ("TaxaFixa" >= 0),
  "Ativo"          smallint      NOT NULL DEFAULT 1,
  "Ordem"          integer       NOT NULL DEFAULT 0
);

-- 7. Cliente
CREATE TABLE IF NOT EXISTS "Cliente" (
  "Id"           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmpresaId"    integer      NOT NULL REFERENCES "Empresa"("Id"),
  "Nome"         varchar(120) NOT NULL,
  "Telefone"     varchar(20)  NULL,
  "Documento"    varchar(20)  NULL,
  "Observacao"   varchar(500) NULL,
  "Ativo"        smallint     NOT NULL DEFAULT 1,
  "DataCadastro" timestamp(0) NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo')
);

-- 8. Venda (valor líquido e lucro calculados pelo banco)
CREATE TABLE IF NOT EXISTS "Venda" (
  "Id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmpresaId"        integer       NOT NULL REFERENCES "Empresa"("Id"),
  "UsuarioId"        integer       NOT NULL REFERENCES "Usuario"("Id"),
  "ClienteId"        integer       NULL REFERENCES "Cliente"("Id"),
  "FormaPagamentoId" integer       NOT NULL REFERENCES "FormaPagamento"("Id"),
  "DataVenda"        timestamp(0)  NOT NULL,
  "ValorBruto"       numeric(12,2) NOT NULL CHECK ("ValorBruto" >= 0),
  "Desconto"         numeric(12,2) NOT NULL DEFAULT 0,
  "ValorTaxa"        numeric(12,2) NOT NULL DEFAULT 0,
  "CustoTotal"       numeric(12,2) NOT NULL DEFAULT 0,
  "ValorLiquido"     numeric(12,2) GENERATED ALWAYS AS ("ValorBruto" - "Desconto") STORED,
  "Lucro"            numeric(12,2) GENERATED ALWAYS AS ("ValorBruto" - "Desconto" - "ValorTaxa" - "CustoTotal") STORED,
  "Status"           varchar(10)   NOT NULL DEFAULT 'CONCLUIDA' CHECK ("Status" IN ('CONCLUIDA','CANCELADA')),
  "Observacao"       varchar(500)  NULL,
  "DataCancelamento" timestamp(0)  NULL,
  CONSTRAINT "CK_Venda_Desconto" CHECK ("Desconto" >= 0 AND "Desconto" <= "ValorBruto")
);

-- 9. ItemVenda
CREATE TABLE IF NOT EXISTS "ItemVenda" (
  "Id"            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmpresaId"     integer       NOT NULL REFERENCES "Empresa"("Id"),
  "VendaId"       integer       NOT NULL REFERENCES "Venda"("Id"),
  "ProdutoId"     integer       NOT NULL REFERENCES "Produto"("Id"),
  "Quantidade"    integer       NOT NULL CHECK ("Quantidade" > 0),
  "PrecoUnitario" numeric(12,2) NOT NULL,
  "CustoUnitario" numeric(12,2) NOT NULL
);

-- 10. ParcelaCrediario
CREATE TABLE IF NOT EXISTS "ParcelaCrediario" (
  "Id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmpresaId"      integer       NOT NULL REFERENCES "Empresa"("Id"),
  "VendaId"        integer       NOT NULL REFERENCES "Venda"("Id"),
  "ClienteId"      integer       NOT NULL REFERENCES "Cliente"("Id"),
  "Numero"         integer       NOT NULL,
  "TotalParcelas"  integer       NOT NULL,
  "Valor"          numeric(12,2) NOT NULL CHECK ("Valor" > 0),
  "DataVencimento" date          NOT NULL,
  "DataPagamento"  timestamp(0)  NULL,
  "ValorPago"      numeric(12,2) NULL,
  "Status"         varchar(10)   NOT NULL DEFAULT 'ABERTA' CHECK ("Status" IN ('ABERTA','PAGA','CANCELADA'))
);

-- Índices
CREATE INDEX IF NOT EXISTS "IX_Venda_Empresa_Data" ON "Venda" ("EmpresaId", "DataVenda");
CREATE INDEX IF NOT EXISTS "IX_Produto_Empresa_Ativo" ON "Produto" ("EmpresaId", "Ativo");
CREATE INDEX IF NOT EXISTS "IX_Cliente_Empresa_Nome" ON "Cliente" ("EmpresaId", "Nome");
CREATE INDEX IF NOT EXISTS "IX_Parcela_Empresa_Status_Venc" ON "ParcelaCrediario" ("EmpresaId", "Status", "DataVencimento");
CREATE INDEX IF NOT EXISTS "IX_ItemVenda_Venda" ON "ItemVenda" ("VendaId");
CREATE INDEX IF NOT EXISTS "IX_Categoria_Empresa" ON "Categoria" ("EmpresaId");
CREATE INDEX IF NOT EXISTS "IX_FormaPagamento_Empresa" ON "FormaPagamento" ("EmpresaId");

-- View: parcelas com nome e telefone do cliente, situação calculada (ABERTA, ATRASADA, PAGA)
-- e dias de atraso. "Hoje" é a data de Brasília. Canceladas ficam de fora.
CREATE OR REPLACE VIEW "vw_ParcelasCrediario" AS
SELECT p."Id", p."EmpresaId", p."VendaId", p."ClienteId",
       c."Nome" AS "ClienteNome", c."Telefone" AS "ClienteTelefone",
       p."Numero", p."TotalParcelas", p."Valor", p."DataVencimento", p."DataPagamento", p."ValorPago",
       CASE WHEN p."Status" = 'PAGA' THEN 'PAGA'
            WHEN p."DataVencimento" < (now() AT TIME ZONE 'America/Sao_Paulo')::date THEN 'ATRASADA'
            ELSE 'ABERTA' END::varchar(10) AS "Situacao",
       CASE WHEN p."Status" = 'ABERTA' AND p."DataVencimento" < (now() AT TIME ZONE 'America/Sao_Paulo')::date
            THEN (now() AT TIME ZONE 'America/Sao_Paulo')::date - p."DataVencimento"
            ELSE 0 END AS "DiasAtraso"
FROM "ParcelaCrediario" p
JOIN "Cliente" c ON c."Id" = p."ClienteId"
WHERE p."Status" <> 'CANCELADA';

